// Writes adapters/opencode-v2/src/core/ from the hosted-core modules OpenCode
// V2 imports. OpenCode installs that package from a Git subdirectory
// (`::path:adapters/opencode-v2`), which can't reach a sibling directory, so it
// carries a generated copy; tests/integration/hosted_core_sync.test.ts fails
// when the copy drifts. lock, login, storage, proxy, channel and
// native-tools.json stay out: dead code there (OpenCode owns the grant and
// the storage), and proxy imports the repo's src/, outside opencode-v2's
// `rootDir: src` build.
import { readdirSync, readFileSync, rmSync, writeFileSync, mkdirSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
export const SOURCE = join(root, "adapters/hosted-core/src");
export const TARGET = join(root, "adapters/opencode-v2/src/core");
export const VENDORED = ["port", "wire", "model", "sessions", "events", "diagnostics", "controller", "children"] as const;

const header = (module: string) => `// Generated by scripts/sync_hosted_core.ts from adapters/hosted-core/src/${module}.ts.\n// Do not edit: change hosted-core, then run \`bun scripts/sync_hosted_core.ts\`.\n`;

// The copy, keyed by file name. Refuses a vendored module whose relative
// imports leave the vendored set, so the copy always compiles on its own.
export function generated(): Map<string, string> {
  const files = new Map<string, string>();
  for (const module of VENDORED) {
    const source = readFileSync(join(SOURCE, `${module}.ts`), "utf8");
    for (const [, specifier] of source.matchAll(/from "(\.[^"]+)"/g)) {
      const target = /^\.\/([a-z-]+)\.js$/.exec(specifier!)?.[1];
      if (!target || !(VENDORED as readonly string[]).includes(target)) throw new Error(`hosted-core ${module}.ts imports ${specifier}, outside the vendored set`);
    }
    files.set(`${module}.ts`, header(module) + source);
  }
  return files;
}

if (import.meta.main) {
  const files = generated();
  mkdirSync(TARGET, { recursive: true });
  for (const name of readdirSync(TARGET)) if (!files.has(name)) rmSync(join(TARGET, name));
  for (const [name, text] of files) writeFileSync(join(TARGET, name), text);
  console.log(`wrote ${files.size} modules to ${TARGET}`);
}
