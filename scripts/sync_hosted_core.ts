// Writes adapters/opencode-v2/src/core/ from the hosted-core modules OpenCode
// V2 imports. OpenCode installs that package from a Git subdirectory
// (`::path:adapters/opencode-v2`), which can't reach a sibling directory, so it
// carries a generated copy; tests/integration/hosted_core_sync.test.ts fails
// when the copy drifts. Attachment transfers also carry their shared path,
// digest and deadline helpers. Grant ownership and tool forwarding remain native.
import { readdirSync, readFileSync, rmSync, writeFileSync, mkdirSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
export const SOURCE = join(root, "adapters/hosted-core/src");
export const TARGET = join(root, "adapters/opencode-v2/src/core");
export const VENDORED = ["port", "wire", "model", "sessions", "events", "diagnostics", "controller", "children", "attachments", "results"] as const;
const SHARED = {
  "../../../src/shared/attachments.ts": ["attachment-files", "src/shared/attachments.ts"],
  "../../../src/shared/http.ts": ["http", "src/shared/http.ts"],
  "../core/errors.ts": ["attachment-errors", "src/core/errors.ts"],
  "./hash.ts": ["attachment-hash", "src/shared/hash.ts"],
} as const;

const header = (module: string) => `// Generated by scripts/sync_hosted_core.ts from adapters/hosted-core/src/${module}.ts.\n// Do not edit: change hosted-core, then run \`bun scripts/sync_hosted_core.ts\`.\n`;

// The copy, keyed by file name. Refuses a vendored module whose relative
// imports leave the vendored set, so the copy always compiles on its own.
export function generated(): Map<string, string> {
  const files = new Map<string, string>();
  const sources = [
    ...VENDORED.map(module => [module, `adapters/hosted-core/src/${module}.ts`] as const),
    ...Object.values(SHARED),
  ];
  for (const [module, path] of sources) {
    const source = readFileSync(join(root, path), "utf8").replace(/from "(\.[^"]+)"/g, (statement, specifier: string) => {
      const shared = SHARED[specifier as keyof typeof SHARED];
      if (shared) return `from "./${shared[0]}.js"`;
      const target = /^\.\/([a-z-]+)\.js$/.exec(specifier)?.[1];
      if (!target || !(VENDORED as readonly string[]).includes(target)) throw new Error(`${path} imports ${specifier}, outside the vendored set`);
      return statement;
    });
    const provenance = path.startsWith("adapters/hosted-core/src/") ? header(module) : `// Generated by scripts/sync_hosted_core.ts from ${path}.\n// Do not edit: change the source, then run \`bun scripts/sync_hosted_core.ts\`.\n`;
    files.set(`${module}.ts`, provenance + source);
  }
  return files;
}

if (import.meta.main) {
  const files = generated();
  mkdirSync(TARGET, { recursive: true });
  for (const name of readdirSync(TARGET)) if (!files.has(name)) rmSync(join(TARGET, name));
  for (const [name, text] of files) writeFileSync(join(TARGET, name), text);
  console.log(`wrote ${files.size} modules to ${TARGET}`);
}
