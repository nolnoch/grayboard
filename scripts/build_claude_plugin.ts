// Writes plugins/claude-code/dist/grayboard.js, the Claude Code plugin's one
// executable (#281), bundled from plugins/claude-code/src/main.ts for bun.
// Claude Code installs the plugin from a Git subdirectory and runs no build,
// so the bundle is committed; tests/integration/claude_plugin_package.test.ts
// fails when it differs from a fresh build. It carries package.json's
// version, so a version bump reruns this script.
//
// Built from the repo root: the bundle's module comments are cwd-relative
// paths, and a build from another cwd would embed the builder's absolute paths.
//
// Every bare import resolves from the repo root, the plugin's one lockfile.
// adapters/hosted-core is an independent package whose own gate
// (`bun run test:opencode`) installs adapters/hosted-core/node_modules; left to
// default resolution, hosted-core's imports would bind to that install when it
// exists, so the bundle would depend on an untracked directory and carry a
// second zod and MCP client beside the root copies.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import type { BunPlugin } from "bun";

const root = resolve(import.meta.dir, "..");
export const BUNDLE = join(root, "plugins/claude-code/dist/grayboard.js");
const HEADER = "// Generated by scripts/build_claude_plugin.ts from plugins/claude-code/src/. Do not edit: change the source, then run `bun scripts/build_claude_plugin.ts`.\n";

// An import of one of hosted-core's declared dependencies (or a subpath of
// one) from hosted-core's own files resolves as though imported from this
// script, whose nearest node_modules is the repo root's. import.meta.resolve
// applies ESM `import` conditions, as the bundler does. The filter names only
// those packages because Bun drops a package's `sideEffects` tree shaking for
// every specifier an onResolve filter matches, even when the callback returns
// nothing. Every other import keeps the bundler's own resolution.
const hostedCore = join(root, "adapters/hosted-core") + "/";
const hostedCoreDependencies = Object.keys(JSON.parse(readFileSync(join(hostedCore, "package.json"), "utf8")).dependencies ?? {});
const escapeRegExp = (s: string) => s.replace(/[.*+?^${}()|[\]\\/]/g, "\\$&");
const rootDependencies: BunPlugin = {
  name: "root-dependencies",
  setup(build) {
    if (hostedCoreDependencies.length === 0) return;
    const filter = new RegExp(`^(${hostedCoreDependencies.map(escapeRegExp).join("|")})(/|$)`);
    build.onResolve({ filter }, (args) => (args.importer.startsWith(hostedCore) ? { path: Bun.fileURLToPath(import.meta.resolve(args.path)) } : undefined));
  },
};

// The bundle's text. Bun's `// @bun` pragma must stay the first line, so the
// header follows it.
export async function bundle(): Promise<string> {
  const r = await Bun.build({ entrypoints: [join(root, "plugins/claude-code/src/main.ts")], root, target: "bun", format: "esm", plugins: [rootDependencies], throw: false });
  if (!r.success) throw new Error(`bundling plugins/claude-code/src/main.ts failed: ${r.logs.map(String).join("\n")}`);
  const text = await r.outputs[0]!.text();
  const pragma = "// @bun\n";
  return text.startsWith(pragma) ? pragma + HEADER + text.slice(pragma.length) : HEADER + text;
}

if (import.meta.main) {
  const text = await bundle();
  mkdirSync(dirname(BUNDLE), { recursive: true });
  writeFileSync(BUNDLE, text);
  console.log(`wrote ${BUNDLE} (${text.length} bytes)`);
}
