// Writes plugins/claude-code/dist/grayboard.js, the Claude Code plugin's one
// executable (#281), bundled from plugins/claude-code/src/main.ts for bun.
// Claude Code installs the plugin from a Git subdirectory and runs no build,
// so the bundle is committed; tests/integration/claude_plugin_package.test.ts
// fails when it differs from a fresh build. It carries package.json's
// version, so a version bump reruns this script.
//
// Built from the repo root: the bundle's module comments are cwd-relative
// paths, and a build from another cwd would embed the builder's absolute paths.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
export const BUNDLE = join(root, "plugins/claude-code/dist/grayboard.js");
const HEADER = "// Generated by scripts/build_claude_plugin.ts from plugins/claude-code/src/. Do not edit: change the source, then run `bun scripts/build_claude_plugin.ts`.\n";

// The bundle's text. Bun's `// @bun` pragma must stay the first line, so the
// header follows it.
export function bundle(): string {
  const r = Bun.spawnSync([process.execPath, "build", "plugins/claude-code/src/main.ts", "--target=bun", "--format=esm"], { cwd: root, stdout: "pipe", stderr: "pipe" });
  if (r.exitCode !== 0) throw new Error(`bundling plugins/claude-code/src/main.ts failed (exit ${r.exitCode}): ${r.stderr.toString()}`);
  const text = r.stdout.toString();
  const pragma = "// @bun\n";
  return text.startsWith(pragma) ? pragma + HEADER + text.slice(pragma.length) : HEADER + text;
}

if (import.meta.main) {
  const text = bundle();
  mkdirSync(dirname(BUNDLE), { recursive: true });
  writeFileSync(BUNDLE, text);
  console.log(`wrote ${BUNDLE} (${text.length} bytes)`);
}
